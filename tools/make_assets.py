#!/usr/bin/env python3
"""Generate the восьминіг assets: octopus sprite (JS), opening sound (WAV) and app icons.

    python tools/make_assets.py

Writes app/ui/sprite.js, app/ui/octopus.wav, app/assets/icon.png|.icns|.ico
Everything is drawn / synthesised here, so there is nothing to license.
"""
import json
import math
import os
import shutil
import struct
import subprocess
import tempfile
import wave

from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UI = os.path.join(ROOT, "app", "ui")
ASSETS = os.path.join(ROOT, "app", "assets")

# --------------------------------------------------------------------------
# Sprite: 23 x 17 pixels, 8 tentacles, two animation frames
# --------------------------------------------------------------------------
BODY = [
    "........MMMMMMM........",
    "......MMMMMMMMMMM......",
    ".....MMHHMMMMMMMMM.....",
    "....MMHHMMMMMMMMMMM....",
    "....MHMMMMMMMMMMMMM....",
    "...MMMMMMMMMMMMMMMMM...",
    "...MMWWWMMMMMMMWWWMM...",
    "...MMWKKMMMMMMMWKKMM...",
    "...MMWKKMMMMMMMWKKMM...",
    "...MMMMMMMMMMMMMMMMM...",
    "...MMMCCMMDDDMMCCMMM...",
    "....MMMMMMMMMMMMMMM....",
    "...MMMMMMMMMMMMMMMMM...",
    "MM.MM.MM.MM.MM.MM.MM.MM",
    "MM.MM.MM.MM.MM.MM.MM.MM",
]
FRAMES = [
    BODY + ["M..M..M..M..M..M..M..M.", ".M..M..M..M..M..M..M..M"],
    BODY + [".M..M..M..M..M..M..M..M", "M..M..M..M..M..M..M..M."],
]
PALETTE = {"M": "#ff2bd6", "H": "#ff9cf0", "W": "#ffffff", "K": "#1a0033", "C": "#ff6fa8", "D": "#7a0060"}
for f in FRAMES:
    assert all(len(r) == 23 for r in f), [len(r) for r in f]


def write_sprite_js():
    js = ("// Generated by tools/make_assets.py - the восьминіг octopus\n"
          f"window.OCTO = {json.dumps({'frames': FRAMES, 'palette': PALETTE})};\n")
    with open(os.path.join(UI, "sprite.js"), "w", encoding="utf-8") as fh:
        fh.write(js)


# --------------------------------------------------------------------------
# Opening sound: bubbles, a wobbly "glorp", an arcade sting (~1.7 s, 8-bit flavour)
# --------------------------------------------------------------------------
SR = 22050


def synth_octopus() -> list:
    out = [0.0] * int(SR * 1.75)

    def voice(start, dur, freq, vol, wave_="square", duty=0.5, attack=0.004, curve=1.6):
        phase = 0.0
        n = int(dur * SR)
        for i in range(n):
            u = i / n
            phase += freq(u, i / SR) / SR
            ph = phase % 1.0
            v = (1.0 if ph < duty else -1.0) if wave_ == "square" else 4 * abs(ph - 0.5) - 1
            env = min(1.0, (i / SR) / attack) * (1 - u) ** curve
            j = int(start * SR) + i
            if j < len(out):
                out[j] += v * vol * env

    # rising bubbles: bloop-bloop-bloop
    for k, t0 in enumerate((0.00, 0.10, 0.18, 0.245)):
        lo, hi = 320 * 1.18 ** k, 1050 * 1.18 ** k
        voice(t0, 0.065, lambda u, t, lo=lo, hi=hi: lo * (hi / lo) ** u, 0.26)
    # the glorp: low, sliding down, wobbling like a happy cephalopod
    voice(0.34, 0.58, lambda u, t: 240 * (1 - 0.48 * u) * (1 + 0.2 * math.sin(2 * math.pi * 13 * t)), 0.42,
          wave_="square", duty=0.32, attack=0.02, curve=0.9)
    voice(0.34, 0.58, lambda u, t: 120 * (1 - 0.48 * u), 0.22, wave_="tri", attack=0.02, curve=0.9)
    # two last pops
    voice(0.93, 0.05, lambda u, t: 600 * 2.2 ** u, 0.2)
    voice(0.99, 0.05, lambda u, t: 800 * 2.2 ** u, 0.2)
    # arcade sting: C5 E5 G5 C6 (pulse 25%), last note with vibrato
    for k, f in enumerate((523.25, 659.25, 783.99)):
        voice(1.08 + k * 0.075, 0.075, lambda u, t, f=f: f, 0.2, duty=0.25, curve=0.4)
    voice(1.305, 0.42, lambda u, t: 1046.5 * (1 + 0.012 * math.sin(2 * math.pi * 7 * t)), 0.2, duty=0.25, curve=1.2)

    peak = max(abs(v) for v in out) or 1.0
    return [round(v / peak * 0.85 * 32) / 32 for v in out]       # 6-bit crunch


def write_wav(samples, path):
    with wave.open(path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(b"".join(struct.pack("<h", int(max(-1, min(1, v)) * 32000)) for v in samples))


# --------------------------------------------------------------------------
# Icons
# --------------------------------------------------------------------------
def draw_icon(size=1024) -> Image.Image:
    inset, radius = int(size * 0.098), int(size * 0.18)              # macOS icon grid
    box = (inset, inset, size - inset, size - inset)
    # background + synthwave floor, clipped to the rounded square
    bg = Image.new("RGBA", (size, size), "#12052e")
    d = ImageDraw.Draw(bg)
    top = int(size * 0.68)
    lw = max(2, size // 300)
    for y in range(top, size, int(size * 0.035)):
        d.line([(0, y), (size, y)], fill="#3a0f6b", width=lw)
    for k in range(-8, 9):
        d.line([(size / 2 + k * size * 0.03, top), (size / 2 + k * size * 0.11, size)], fill="#3a0f6b", width=lw)
    mask = Image.new("L", (size, size), 0)
    ImageDraw.Draw(mask).rounded_rectangle(box, radius, fill=255)
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    img.paste(bg, (0, 0), mask)
    d = ImageDraw.Draw(img)
    d.rounded_rectangle(box, radius, outline="#22e8ff", width=max(6, size // 64))
    # the octopus
    px = int(size * 0.029)
    frame = FRAMES[0]
    w = len(frame[0]) * px
    ox, oy = (size - w) // 2, int(size * 0.24)
    for r, row in enumerate(frame):
        for c, ch in enumerate(row):
            if ch != ".":
                d.rectangle([ox + c * px, oy + r * px, ox + (c + 1) * px - 1, oy + (r + 1) * px - 1], fill=PALETTE[ch])
    # bubbles rising from the octopus
    for bx, by, bs in ((0.70, 0.215, 2), (0.755, 0.165, 1), (0.69, 0.155, 1)):
        x0, y0, s = int(size * bx), int(size * by), px * bs
        d.rectangle([x0, y0, x0 + s, y0 + s], outline="#22e8ff", width=max(3, px // 3))
    return img


def write_icons():
    os.makedirs(ASSETS, exist_ok=True)
    icon = draw_icon(1024)
    icon.save(os.path.join(ASSETS, "icon.png"))
    icon.save(os.path.join(ASSETS, "icon.ico"), sizes=[(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)])
    if shutil.which("iconutil"):
        tmp = tempfile.mkdtemp()
        iconset = os.path.join(tmp, "icon.iconset")
        os.makedirs(iconset)
        for base in (16, 32, 128, 256, 512):
            icon.resize((base, base), Image.LANCZOS).save(os.path.join(iconset, f"icon_{base}x{base}.png"))
            icon.resize((base * 2, base * 2), Image.LANCZOS).save(os.path.join(iconset, f"icon_{base}x{base}@2x.png"))
        subprocess.run(["iconutil", "-c", "icns", iconset, "-o", os.path.join(ASSETS, "icon.icns")], check=True)
        shutil.rmtree(tmp)


if __name__ == "__main__":
    os.makedirs(UI, exist_ok=True)
    write_sprite_js()
    write_wav(synth_octopus(), os.path.join(UI, "octopus.wav"))
    write_icons()
    print("assets written to", os.path.relpath(UI, ROOT), "and", os.path.relpath(ASSETS, ROOT))
